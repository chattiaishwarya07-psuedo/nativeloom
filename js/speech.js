export const AudioAssistance = {
  // Read saved preference from localStorage, default to true (ON)
  isEnabled: typeof localStorage !== 'undefined'
    ? localStorage.getItem('nl_voice_guide_enabled') !== 'false'
    : true,
  isSpeaking: false,
  _summaryTimer: null,

  /**
   * Set Voice Guide ON or OFF explicitly
   */
  setEnabled(val) {
    this.isEnabled = !!val;
    try {
      if (typeof localStorage !== 'undefined') {
        localStorage.setItem('nl_voice_guide_enabled', this.isEnabled ? 'true' : 'false');
      }
    } catch (e) {}

    if (!this.isEnabled) {
      this.stop();
      if (typeof window !== 'undefined' && window.showToast) {
        window.showToast("🔇 Voice Guide turned OFF (Speech muted)");
      }
    } else {
      if (typeof window !== 'undefined' && window.showToast) {
        window.showToast("🔊 Voice Guide turned ON (Audio active)");
      }
      // Immediately speak the current screen summary when turned ON
      const cur = (typeof window !== 'undefined' && window.State && window.State.currentScreen) || 'home';
      this.speakPageSummary(cur);
    }

    this.updateAllTogglesUI();
    if (typeof window !== 'undefined') {
      window.dispatchEvent(new CustomEvent('voiceguidechange', { detail: { isEnabled: this.isEnabled } }));
    }
    return this.isEnabled;
  },

  /**
   * Toggle Voice Guide ON <-> OFF
   */
  toggle() {
    return this.setEnabled(!this.isEnabled);
  },

  /**
   * Updates all Voice Guide toggle buttons across all screens in the DOM
   */
  updateAllTogglesUI() {
    if (typeof document === 'undefined') return;
    const toggles = document.querySelectorAll('.voice-guide-toggle-btn, #btn-voice-guide-toggle, #btn-global-audio, #screen-audio-btn, #splash-voice-guide-btn, #discover-voice-guide-btn');

    const speakerOnSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="#7A2813" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round" style="display:inline-block; vertical-align:middle;"><polygon points="11 5 6 9 2 9 2 15 6 15 11 19 11 5"/><path d="M15.54 8.46a5 5 0 0 1 0 7.07"/><path d="M19.07 4.93a10 10 0 0 1 0 14.14"/></svg>`;
    const speakerOffSvg = `<svg xmlns="http://www.w3.org/2000/svg" width="13" height="13" viewBox="0 0 24 24" fill="none" stroke="#7A2813" stroke-width="2.3" stroke-linecap="round" stroke-linejoin="round" style="display:inline-block; vertical-align:middle;"><line x1="1" y1="1" x2="23" y2="23"/><polygon points="11 5 6 9 2 9 2 15 6 15 11 19 11 5"/><path d="M15.54 8.46a5 5 0 0 1 1.7 4.54"/><path d="M19.07 4.93a10 10 0 0 1 .82 12.06"/></svg>`;

    toggles.forEach(btn => {
      if (!btn) return;
      if (this.isEnabled) {
        btn.classList.add('vg-on');
        btn.classList.remove('vg-off');
        btn.setAttribute('aria-pressed', 'true');
        btn.setAttribute('title', 'Voice Guide is ON (Click to turn OFF)');
        btn.innerHTML = `
          <span class="vg-icon" style="display:inline-flex; align-items:center;">${speakerOnSvg}</span>
          <span class="vg-label" style="font-size:0.72rem; font-weight:800; letter-spacing:0.01em; color:#7A2813;">Voice: ON</span>
        `;
      } else {
        btn.classList.add('vg-off');
        btn.classList.remove('vg-on');
        btn.setAttribute('aria-pressed', 'false');
        btn.setAttribute('title', 'Voice Guide is OFF (Click to turn ON)');
        btn.innerHTML = `
          <span class="vg-icon" style="display:inline-flex; align-items:center;">${speakerOffSvg}</span>
          <span class="vg-label" style="font-size:0.72rem; font-weight:800; letter-spacing:0.01em; color:#7A2813;">Voice: OFF</span>
        `;
      }
    });
  },

  /**
   * Helper to pick the best speech synthesis voice for the target Indian locale
   */
  getBestVoice(targetLocale) {
    if (typeof window === 'undefined' || !('speechSynthesis' in window)) return null;
    const voices = window.speechSynthesis.getVoices();
    if (!voices || !voices.length) return null;

    const norm = (targetLocale || '').toLowerCase().replace('_', '-');
    const primary = norm.split('-')[0];

    // 1. Exact match on full locale
    let match = voices.find(v => (v.lang || '').toLowerCase().replace('_', '-') === norm);
    if (match) return match;

    // 2. Primary language tag match (e.g., 'hi', 'ta', 'te', 'bn')
    match = voices.find(v => (v.lang || '').toLowerCase().startsWith(primary + '-'));
    if (match) return match;

    // 3. Indian English match
    if (primary === 'en') {
      match = voices.find(v => (v.lang || '').toLowerCase().includes('en-in') || (v.lang || '').toLowerCase().includes('en-gb') || (v.lang || '').toLowerCase().includes('en-us'));
      if (match) return match;
    }

    // 4. Fallback to any Indian voice (hi-IN) for regional Indian scripts if native TTS is missing
    match = voices.find(v => (v.lang || '').toLowerCase().includes('hi-in') || (v.lang || '').toLowerCase().includes('in'));
    return match || null;
  },

  /**
   * Low-level speech synthesizer execution. Strictly suppressed when isEnabled is false.
   */
  speak(text, lang = null) {
    if (!this.isEnabled) {
      console.log("Voice Guide is OFF: speech suppressed for text:", text);
      return;
    }
    if (!text) return;
    const targetLocale = lang || (i18n && i18n.getVoiceLocale ? i18n.getVoiceLocale() : 'en-IN');

    if (typeof window === 'undefined' || !('speechSynthesis' in window)) {
      console.log("Audio assistance (no Web Speech API):", text);
      return;
    }

    try {
      window.speechSynthesis.cancel();
      const utterance = new SpeechSynthesisUtterance(text);
      utterance.lang = targetLocale;
      utterance.rate = 0.95;
      utterance.pitch = 1.0;

      const voice = this.getBestVoice(targetLocale);
      if (voice) {
        utterance.voice = voice;
      }

      utterance.onstart = () => {
        this.isSpeaking = true;
        document.body.classList.add('audio-playing');
      };

      utterance.onend = () => {
        this.isSpeaking = false;
        document.body.classList.remove('audio-playing');
      };

      utterance.onerror = () => {
        this.isSpeaking = false;
        document.body.classList.remove('audio-playing');
      };

      window.speechSynthesis.speak(utterance);
    } catch (e) {
      console.warn("Speech synthesis error:", e);
    }
  },

  /**
   * Canonicalizes any screen name or alias into a standard dictionary key
   */
  canonicalScreen(screenName) {
    if (!screenName) return 'explore';
    const s = String(screenName).toLowerCase().trim();
    const role = (typeof window !== 'undefined' && window.State && (window.State.mode || (window.State.session && window.State.session.accountType))) || '';

    if (s === 'home') {
      if (role === 'corporate') return 'wholesale';
      if (role === 'seller' || role === 'artisan') return 'studio';
      return 'explore';
    }
    if (s === 'orders') {
      if (role === 'corporate') return 'corporate_quotes';
      if (role === 'seller' || role === 'artisan') return 'artisan_orders';
      return 'orders';
    }
    if (s === 'profile') {
      if (role === 'corporate') return 'corporate_profile';
      if (role === 'seller' || role === 'artisan') return 'artisan_profile';
      return 'buyer_profile';
    }
    if (s === 'search') {
      if (role === 'corporate') return 'corporate_catalog';
      if (role === 'seller' || role === 'artisan') return 'artisan_discover';
      return 'search';
    }

    const aliasMap = {
      'languages': 'language_select',
      'artisan_studio': 'studio',
      'artisan_inventory': 'manage_crafts',
      'bank': 'bank',
      'artisan_bank': 'bank',
      'pehchan': 'pehchan',
      'artisan_pehchan': 'pehchan',
      'welcome_identity': 'welcome',
      'artisan_auth': 'welcome',
      'buyer_explore': 'explore',
      'cart': 'cart_review',
      'buyer_orders': 'orders',
      'buyer_returns': 'returns_policy',
      'corporate_clusters': 'wholesale',
      'chat': 'artisan_chat'
    };

    return aliasMap[s] || s;
  },

  /**
   * Resolves concise high-level page summary for a screen in the given language
   */
  getPageSummaryText(screenName, lang = 'en') {
    if (!screenName) return null;
    const cleanScreen = this.canonicalScreen(screenName);

    // 1. Check target language
    if (PageSummaries[lang] && PageSummaries[lang][cleanScreen]) {
      return PageSummaries[lang][cleanScreen];
    }

    // 2. Primary fallback to English
    if (PageSummaries.en && PageSummaries.en[cleanScreen]) {
      return PageSummaries.en[cleanScreen];
    }

    // 3. Secondary fallback to Hindi
    if (lang !== 'hi' && PageSummaries.hi && PageSummaries.hi[cleanScreen]) {
      return PageSummaries.hi[cleanScreen];
    }

    return null;
  },

  /**
   * Speaks the concise high-level summary of the current page.
   * Strictly played ONLY if Voice Guide toggle is ON.
   * Does not read individual lines or list items.
   */
  speakPageSummary(screenName) {
    if (!this.isEnabled) {
      return;
    }
    if (!screenName) return;

    if (this._summaryTimer) {
      clearTimeout(this._summaryTimer);
      this._summaryTimer = null;
    }

    const currentLang = (typeof window !== 'undefined' && window.State && window.State.language)
      || (i18n && i18n.currentLang)
      || 'en';

    const summaryText = this.getPageSummaryText(screenName, currentLang);
    if (!summaryText) return;

    const meta = LanguageMetadata && LanguageMetadata[currentLang];
    const targetLocale = meta?.voiceLocale || 'en-IN';

    // Delay slightly to let screen finish rendering before voice starts
    this._summaryTimer = setTimeout(() => {
      if (this.isEnabled) {
        this.speak(summaryText, targetLocale);
      }
    }, 220);
  },

  /**
   * Immediately stops any active speech synthesis audio
   */
  stop() {
    if (this._summaryTimer) {
      clearTimeout(this._summaryTimer);
      this._summaryTimer = null;
    }
    if (typeof window !== 'undefined' && 'speechSynthesis' in window) {
      try {
        window.speechSynthesis.cancel();
      } catch (e) {}
      this.isSpeaking = false;
      document.body.classList.remove('audio-playing');
    }
  }
};

